-- Salidas, solicitudes de cancelación y bitácora de la clase.

ALTER TABLE "PROYECTO_CLASE_ESPEJO"
    ADD COLUMN "motivo_cancelacion" TEXT NOT NULL DEFAULT '',
    ADD COLUMN "cancelado_en" TIMESTAMP(3);

ALTER TABLE "PROYECTO_PARTICIPANTE"
    ADD COLUMN "retirado_en" TIMESTAMP(3),
    ADD COLUMN "motivo_salida" TEXT NOT NULL DEFAULT '';

CREATE TABLE "PROYECTO_EVENTO" (
    "id" SERIAL NOT NULL,
    "proyecto_id" INTEGER NOT NULL,
    "participante_id" INTEGER,
    "tipo" TEXT NOT NULL,
    "motivo" TEXT NOT NULL DEFAULT '',
    "actor_usuario_id" INTEGER,
    "creado_en" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PROYECTO_EVENTO_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "PROYECTO_EVENTO_proyecto_id_creado_en_idx"
    ON "PROYECTO_EVENTO"("proyecto_id", "creado_en");
CREATE INDEX "PROYECTO_EVENTO_participante_id_idx"
    ON "PROYECTO_EVENTO"("participante_id");
CREATE INDEX "PROYECTO_EVENTO_actor_usuario_id_idx"
    ON "PROYECTO_EVENTO"("actor_usuario_id");

ALTER TABLE "PROYECTO_EVENTO"
    ADD CONSTRAINT "PROYECTO_EVENTO_proyecto_id_fkey"
    FOREIGN KEY ("proyecto_id") REFERENCES "PROYECTO_CLASE_ESPEJO"("id")
    ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "PROYECTO_EVENTO"
    ADD CONSTRAINT "PROYECTO_EVENTO_participante_id_fkey"
    FOREIGN KEY ("participante_id") REFERENCES "PROYECTO_PARTICIPANTE"("id")
    ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE "PROYECTO_EVENTO"
    ADD CONSTRAINT "PROYECTO_EVENTO_actor_usuario_id_fkey"
    FOREIGN KEY ("actor_usuario_id") REFERENCES "USUARIO"("id")
    ON DELETE SET NULL ON UPDATE CASCADE;

CREATE TABLE "CANCELACION_SOLICITUD" (
    "id" SERIAL NOT NULL,
    "proyecto_id" INTEGER NOT NULL,
    "solicitada_por_usuario_id" INTEGER NOT NULL,
    "motivo" TEXT NOT NULL,
    "estado" TEXT NOT NULL DEFAULT 'PENDIENTE',
    "creada_en" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "actualizado_en" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "resuelta_en" TIMESTAMP(3),
    CONSTRAINT "CANCELACION_SOLICITUD_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "CANCELACION_SOLICITUD_proyecto_id_estado_idx"
    ON "CANCELACION_SOLICITUD"("proyecto_id", "estado");
CREATE INDEX "CANCELACION_SOLICITUD_solicitada_por_usuario_id_idx"
    ON "CANCELACION_SOLICITUD"("solicitada_por_usuario_id");

ALTER TABLE "CANCELACION_SOLICITUD"
    ADD CONSTRAINT "CANCELACION_SOLICITUD_proyecto_id_fkey"
    FOREIGN KEY ("proyecto_id") REFERENCES "PROYECTO_CLASE_ESPEJO"("id")
    ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "CANCELACION_SOLICITUD"
    ADD CONSTRAINT "CANCELACION_SOLICITUD_solicitada_por_usuario_id_fkey"
    FOREIGN KEY ("solicitada_por_usuario_id") REFERENCES "USUARIO"("id")
    ON DELETE RESTRICT ON UPDATE CASCADE;

CREATE TABLE "CANCELACION_VOTO" (
    "id" SERIAL NOT NULL,
    "solicitud_id" INTEGER NOT NULL,
    "participante_id" INTEGER NOT NULL,
    "usuario_id" INTEGER NOT NULL,
    "decision" TEXT NOT NULL,
    "motivo" TEXT NOT NULL DEFAULT '',
    "creado_en" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "CANCELACION_VOTO_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "cancelacion_voto_unico"
    ON "CANCELACION_VOTO"("solicitud_id", "participante_id");
CREATE INDEX "CANCELACION_VOTO_participante_id_idx"
    ON "CANCELACION_VOTO"("participante_id");
CREATE INDEX "CANCELACION_VOTO_usuario_id_idx"
    ON "CANCELACION_VOTO"("usuario_id");

ALTER TABLE "CANCELACION_VOTO"
    ADD CONSTRAINT "CANCELACION_VOTO_solicitud_id_fkey"
    FOREIGN KEY ("solicitud_id") REFERENCES "CANCELACION_SOLICITUD"("id")
